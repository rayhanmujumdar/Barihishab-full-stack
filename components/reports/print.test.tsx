import { render, screen, within } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { october, september, year2026 } from "./fixtures";
import { reportDocTitle } from "./format";
import { MonthlyReport } from "./MonthlyReport";
import { PrintFrame } from "./PrintFrame";

vi.mock("next/navigation", () => ({ useRouter: () => ({ push: vi.fn() }), usePathname: () => "/en/reports/monthly/print" }));

const frame = (draft: boolean, pdf = false) => (
  <PrintFrame locale="en" house={october.house} title="Monthly report · October 2026" draft={draft} generatedBy="Rayhan Ahmed" generatedAt="2026-10-20T06:00:00Z" pdf={pdf}>
    <MonthlyReport locale="en" data={draft ? october : september} mode="print" />
  </PrintFrame>
);

describe("reportDocTitle (F6 file names)", () => {
  it("names monthly drafts, final months and years like the PRD", () => {
    expect(reportDocTitle("monthly", october)).toBe("BariHisab-Monthly-2026-10-DRAFT");
    expect(reportDocTitle("monthly", september)).toBe("BariHisab-Monthly-2026-09");
    expect(reportDocTitle("yearly", year2026)).toBe("BariHisab-Yearly-2026");
  });
});

describe("PrintFrame (F4, F5, F6)", () => {
  it("heads every page with house, address, title and Draft status, and watermarks drafts", () => {
    render(frame(true));
    const head = screen.getByTestId("rpt-print-head");
    expect(within(head).getByText("Ahmed Villa")).toBeInTheDocument();
    expect(within(head).getByText("House 12, Road 5, Mirpur")).toBeInTheDocument();
    expect(within(head).getByText("Monthly report · October 2026")).toBeInTheDocument();
    expect(within(head).getByText("Draft · may change")).toBeInTheDocument();
    expect(screen.getByTestId("rpt-watermark")).toHaveTextContent("DRAFT — NOT FINAL");
    expect(screen.getByRole("contentinfo")).toHaveTextContent("Generated by Rayhan Ahmed on 20 Oct 2026, 12:00 · BariHisab");
    expect(screen.queryByText(/Save as PDF/)).toBeNull();
  });

  it("marks final reports Final, without a watermark", () => {
    render(frame(false));
    expect(within(screen.getByTestId("rpt-print-head")).getByText("Final")).toBeInTheDocument();
    expect(screen.queryByTestId("rpt-watermark")).toBeNull();
  });

  it("explains Save as PDF only for the PDF action", () => {
    render(frame(true, true));
    expect(screen.getByText('In the print dialog, choose "Save as PDF" as the destination.')).toBeInTheDocument();
  });
});
